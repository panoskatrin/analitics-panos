from scipy.interpolate import make_interp_spline


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate a static VTS dashboard HTML file.")
    parser.add_argument(
        "json_path",
        nargs="?",
        default="testmeet_analytics.json",
        help="Path to analytics JSON generated by hybrid_vts.py.",
    )
    parser.add_argument(
        "-o",
        "--output",
        help="Output HTML path. Defaults to <json_name>_dashboard.html.",
    )
    return parser.parse_args()


def default_output_path(json_path: str) -> str:
    base, _ = os.path.splitext(json_path)
    return f"{base}_dashboard.html"


def load_json(path: str) -> dict[str, Any]:
    with open(path, "r", encoding="utf-8") as handle:
        payload = json.load(handle)
    if not isinstance(payload, dict):
        raise ValueError("Analytics JSON must contain an object at the top level.")
    return payload


def create_sentiment_timeline_plot(data: dict[str, Any], output_path: str) -> dict[str, Any]:
    """Render the sentiment timeline as a smoothed Matplotlib PNG."""

    rows = (data.get("sentiment") or {}).get("segments") or []
    x_raw = np.array([float(row.get("start_time") or 0) / 60 for row in rows], dtype=float)
    y_raw = np.array([float(row.get("polarity") or 0) for row in rows], dtype=float)

    order = np.argsort(x_raw)
    x_raw = x_raw[order]
    y_raw = y_raw[order]

    unique_x, unique_indices = np.unique(x_raw, return_index=True)
    unique_y = y_raw[unique_indices]

    fig, ax = plt.subplots(figsize=(12, 4.8), facecolor="#111827")
    ax.set_facecolor("#111827")

    interpolated_points = 0
    if len(unique_x) >= 4:
        x_smooth = np.linspace(float(unique_x.min()), float(unique_x.max()), 300)
        spline = make_interp_spline(unique_x, unique_y, k=3)
        y_smooth = np.clip(spline(x_smooth), -1, 1)
        ax.plot(x_smooth, y_smooth, color="#60a5fa", linewidth=3, label="Sentiment")
        interpolated_points = len(x_smooth)
    elif len(unique_x) >= 2:
        x_smooth = np.linspace(float(unique_x.min()), float(unique_x.max()), 300)
        y_smooth = np.interp(x_smooth, unique_x, unique_y)
        ax.plot(x_smooth, y_smooth, color="#60a5fa", linewidth=3, label="Sentiment")
        interpolated_points = len(x_smooth)
    elif len(unique_x) == 1:
        ax.scatter(unique_x, unique_y, color="#60a5fa", s=42, label="Sentiment")
        interpolated_points = 1

    if len(x_raw):
        point_colors = ["#34d399" if value > 0 else "#f87171" if value < 0 else "#fbbf24" for value in y_raw]
        ax.scatter(x_raw, y_raw, color=point_colors, edgecolor="#0f172a", linewidth=0.8, s=28, zorder=3)

    ax.set_xlabel("Time (minutes)", color="#f8fafc", fontsize=14)
    ax.set_ylabel("Sentiment", color="#f8fafc", fontsize=14)
    ax.set_ylim(-1, 1)
    ax.set_yticks([-1, 0, 1])
    ax.set_yticklabels(["Negative", "Neutral", "Positive"], color="#f8fafc", fontsize=12)
    ax.tick_params(axis="x", colors="#f8fafc", labelsize=12)
    ax.grid(True, color="#334155", linewidth=0.8, alpha=0.85)
    ax.legend(facecolor="#111827", edgecolor="#334155", labelcolor="#f8fafc")

    for spine in ax.spines.values():
        spine.set_color("#334155")

    fig.tight_layout()
    fig.savefig(output_path, dpi=160, bbox_inches="tight", facecolor=fig.get_facecolor())
    plt.close(fig)

    return {
        "raw_points": int(len(x_raw)),
        "interpolated_points": int(interpolated_points),
        "x_label": "Time (minutes)",
        "y_tick_labels": ["Negative", "Neutral", "Positive"],
    }


