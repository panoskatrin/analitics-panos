#!/usr/bin/env python3
"""Generate a standalone VTS analytics HTML dashboard from a JSON report.

This avoids Streamlit/pandas dependencies for environments where only the
Python standard library is available.
"""

from __future__ import annotations

import argparse
import html
import json
